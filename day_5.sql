use sqlchallenge;

-- 1. Total sales value
-- Calculate the total sales value from non-cancelled orders

select sum(oi.quantity*oi.unit_price) as total_sales
from order_items oi 
join orders o 
on oi.order_id=o.order_id
where o.status <> 'cancelled';

-- 2. Sales by product category
-- Identify which product categories generate the most sales

select p.category, sum(oi.quantity*oi.unit_price) as total_sales
from order_items oi 
join orders o 
on oi.order_id=o.order_id
join products p
on p.product_id=oi.product_id
where o.status <> 'cancelled'
group by p.category
order by total_sales desc
limit 1;

-- 3. Top 10 products by sales values
-- Find the 10 products generating the most sales value

select p.product_id, sum(oi.quantity*oi.unit_price) as total_sales
from order_items oi 
join orders o 
on oi.order_id=o.order_id
join products p
on oi.product_id=p.product_id
where o.status <> 'cancelled'
group by p.product_id
order by total_sales desc
limit 10;

-- 4. Total quantity sold by product
-- Calculate the total quantity sold for each product

select p.product_id, sum(oi.quantity) as total_quantity
from order_items oi
join products p 
on oi.product_id=p.product_id
join orders o 
on o.order_id=oi.order_id
where o.status <> 'cancelled'
group by p.product_id
order by total_quantity desc;

-- 5. Average selling price by category
-- Calculate the average product selling price in each product

select category, avg(price) as avg_price
from products 
group by category
order by avg_price desc;

-- 6.Sales by sales channel
-- Calculate sales value generated by each sales channel

select channel, sum(oi.quantity*oi.unit_price) as total_sales
from order_items oi 
join orders o 
on oi.order_id=o.order_id
where o.status <> 'cancelled'
group by channel
order by total_sales desc;

-- 7. Estimated product profit
-- Calculated estimated profit by product using the product cost and item selling price

select p.product_id, p.product_name, sum(oi.quantity*(oi.unit_price-p.cost)) as est_profit
from products p 
join order_items oi 
on p.product_id=oi.product_id
join orders o 
on o.order_id=oi.order_id 
where o.status <> 'cancelled'
group by p.product_id, p.product_name
order by est_profit desc;

-- 8. Top 5 categories by quantity sold
-- Find the five categories with the highest total quantity sold

select p.category, sum(oi.quantity) as total_quantity_sold
from order_items oi 
join products p 
on oi.product_id=p.product_id 
join orders o 
on o.order_id=oi.order_id
where o.status <> 'cancelled'
group by p.category
order by total_quantity_sold desc
limit 5;

